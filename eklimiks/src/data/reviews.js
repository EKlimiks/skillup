/** сколько отзывов генерировать по товару */
function countFor(p, r) {
  const base = { iphone: 62, mac: 34, ipad: 30, watch: 26, audio: 48, tv: 16, vision: 7, accessories: 70 }[p.category] || 20
  const priceFactor = p.price > 180000 ? 0.55 : p.price > 100000 ? 0.8 : p.price > 60000 ? 1 : 1.25
  const jitter = 0.7 + r() * 0.7
  return Math.max(4, Math.round(base * priceFactor * jitter))
}

const MONTHS = 24

export function buildReviews(products) {
  const out = []
  let id = 1
  for (const p of products) {
    const r = rng(p.slug.split('').reduce((s, c) => s + c.charCodeAt(0), 7) * 2654435761)
    const mid = MID[p.category] || MID.accessories
    const n = countFor(p, r)

    for (let i = 0; i < n; i++) {
      /* распределение оценок: пятёрок большинство. Средний рейтинг ≈ 4.7 */
      const dice = r()
      const rating = dice < 0.78 ? 5 : dice < 0.93 ? 4 : dice < 0.97 ? 3 : dice < 0.99 ? 2 : 1

      const female = r() < 0.42
      const first = female ? pick(r, FEMALE) : pick(r, MALE)
      const last = pick(r, LAST) + (female ? 'а' : '')
      const author = `${first} ${last}`

      let text
      if (rating >= 4) {
        const parts = [pick(r, OPEN), pick(r, mid)]
        if (r() < 0.26) parts.push(pick(r, STORE))
        parts.push(pick(r, CLOSE))
        text = parts.join(' ')
      } else if (rating === 3) {
        text = `${pick(r, OPEN)} ${pick(r, mid)} ${pick(r, LOW)}`
      } else {
        text = `${pick(r, BAD)} ${pick(r, LOW)}`
      }

      /* даты за последние 24 месяца, свежие чаще */
      const ago = Math.floor(Math.pow(r(), 1.7) * MONTHS)
      const d = new Date()
      d.setMonth(d.getMonth() - ago)
      d.setDate(1 + Math.floor(r() * 27))
      d.setHours(9 + Math.floor(r() * 12), Math.floor(r() * 60), 0, 0)

      out.push({
        id: id++,
        productSlug: p.slug,
        author,
        rating,
        text,
        approved: true,
        helpful: Math.floor(r() * 46),
        createdAt: d.toISOString(),
      })
    }
  }
  return out.sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1))
}

/** средний рейтинг и количество отзывов по товару (только опубликованные) */
export function ratingStats(reviews, slug) {
  const list = reviews.filter((r) => r.productSlug === slug && r.approved)
  if (!list.length) return { rating: 0, reviews: 0, dist: [0, 0, 0, 0, 0] }
  const dist = [0, 0, 0, 0, 0]
  let sum = 0
  for (const r of list) { dist[5 - r.rating]++; sum += r.rating }
  return { rating: Math.round((sum / list.length) * 10) / 10, reviews: list.length, dist }
}
